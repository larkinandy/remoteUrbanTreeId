#!/usr/bin/env python3
"""Audit and summarize the configured one-city geographic-transfer experiment."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from geographic_utils import (
    eligible_city_support,
    load_predictions,
    load_qa_flags,
    metric_set,
    screen_qa,
)


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG = ROOT / "analysis" / "geographic" / "geographic_config.json"
DEFAULT_OUTPUT = ROOT / "outputs" / "reviewer_revision" / "seven_one_city_analysis"


def parse_args() -> argparse.Namespace:
    """Parse portable paths for the frozen geographic experiment."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--one-city-root", type=Path, required=True)
    parser.add_argument(
        "--legacy-stlouis-root", type=Path, default=None,
        help="Optional root for the separately generated historical St. Louis outputs.",
    )
    parser.add_argument("--primary-predictions", type=Path, required=True)
    parser.add_argument("--qa-metadata", type=Path, required=True)
    parser.add_argument("--geographic-config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--minimum-test-records", type=int, default=1000)
    parser.add_argument("--minimum-group-records", type=int, default=10)
    return parser.parse_args()


def source_paths(root: Path, source: str, legacy_stlouis_root: Path | None) -> tuple[Path, Path]:
    """Return outputs generated by ``run_seven_one_city_models.py``."""
    standard = (
        root / "results" / f"{source}_within_city_test_top5" / "ensemble_predictions.npz",
        root / "results" / f"{source}_cross_city_eligible_test_top5" / "ensemble_predictions.npz",
    )
    if all(path.exists() for path in standard):
        return standard
    if source == "stlouis" and legacy_stlouis_root is not None:
        return (
            legacy_stlouis_root / "results" / "stlouis_within_city_test_top5" / "ensemble_predictions.npz",
            legacy_stlouis_root / "results" / "stlouis_trained_other_cities_test_top5" / "ensemble_predictions.npz",
        )
    return standard[0], root / "results" / f"{source}_to_22_cities_test_top5" / "ensemble_predictions.npz"


def main() -> int:
    arguments = parse_args()
    arguments.output_dir.mkdir(parents=True, exist_ok=True)
    configuration = json.loads(arguments.geographic_config.read_text(encoding="utf-8"))
    sources = tuple(str(value) for value in configuration["source_cities"])
    primary = load_predictions(arguments.primary_predictions, "primary")
    targets = eligible_city_support(
        arguments.primary_predictions, arguments.qa_metadata, arguments.minimum_test_records
    )["city"].tolist()
    qa = load_qa_flags(arguments.qa_metadata)

    metric_rows: list[dict] = []
    audits: list[dict] = []
    source_frames: dict[str, pd.DataFrame] = {}
    for source in sources:
        within_path, cross_path = source_paths(
            arguments.one_city_root, source, arguments.legacy_stlouis_root
        )
        for path in (within_path, cross_path):
            if not path.exists():
                raise FileNotFoundError(path)
        within = load_predictions(within_path, "source")
        cross = load_predictions(cross_path, "source")
        cross = cross.loc[cross["city"].isin(targets) & cross["city"].ne(source)].copy()
        predictions = pd.concat([within, cross], ignore_index=True)
        expected = primary.loc[primary["city"].isin(targets)].copy()
        joined = expected.merge(predictions.drop(columns="city"), on="record_key", how="inner", validate="one_to_one")
        joined = joined.merge(qa, on="record_key", validate="one_to_one")
        expected_by_city = expected.groupby("city").size().sort_index()
        actual_by_city = predictions.groupby("city").size().sort_index()
        audits.append({
            "source_city": source,
            "expected_records": len(expected),
            "prediction_records": len(predictions),
            "joined_records": len(joined),
            "target_city_set_exact": set(predictions.city) == set(targets),
            "records_per_city_exact": expected_by_city.equals(actual_by_city),
            "k11_labels_exact": bool(np.array_equal(joined.k11_label_primary, joined.k11_label_source)),
            "collapsed_k6_labels_exact": bool(np.array_equal(
                joined.collapsed_k6_label_primary, joined.collapsed_k6_label_source
            )),
        })
        joined = screen_qa(joined)
        source_frames[source] = joined
        for target, frame in joined.groupby("city", sort=True):
            relation = "within_city" if target == source else "cross_city"
            for space, class_count in (("k11", 11), ("collapsed_k6", 6)):
                for regime in ("source", "primary"):
                    values, _, _ = metric_set(
                        frame[f"{space}_label_{regime}"].to_numpy(),
                        frame[f"{space}_prediction_{regime}"].to_numpy(),
                        class_count,
                        arguments.minimum_group_records,
                    )
                    metric_rows.append({
                        "source_city": source, "target_city": target, "relation": relation,
                        "regime": "one_city" if regime == "source" else "primary",
                        "label_space": space, **values,
                    })

    audit = pd.DataFrame(audits)
    checks = [
        "target_city_set_exact", "records_per_city_exact",
        "k11_labels_exact", "collapsed_k6_labels_exact",
    ]
    if not audit[checks].all().all():
        raise RuntimeError(f"Comparability audit failed:\n{audit.to_string(index=False)}")
    metrics = pd.DataFrame(metric_rows)
    metrics.to_csv(arguments.output_dir / "source_target_metrics_long.csv", index=False)
    audit.to_csv(arguments.output_dir / "comparability_audit.csv", index=False)

    summary_rows: list[dict] = []
    for (source, regime, space), frame in metrics.groupby(["source_city", "regime", "label_space"], sort=True):
        within = frame.loc[frame.relation.eq("within_city")].iloc[0]
        cross = frame.loc[frame.relation.eq("cross_city")]
        pooled_frame = source_frames[source].loc[source_frames[source].city.ne(source)]
        suffix = "source" if regime == "one_city" else "primary"
        pooled, _, _ = metric_set(
            pooled_frame[f"{space}_label_{suffix}"].to_numpy(),
            pooled_frame[f"{space}_prediction_{suffix}"].to_numpy(),
            11 if space == "k11" else 6,
            arguments.minimum_group_records,
        )
        summary_rows.append({
            "source_city": source, "regime": regime, "label_space": space,
            "within_accuracy": within.accuracy,
            "within_macro_f1": within.macro_f1_groups_ge_minimum,
            "within_weighted_f1": within.weighted_f1,
            "cross_city_count": int(len(cross)),
            "cross_city_mean_accuracy": float(cross.accuracy.mean()),
            "cross_city_median_accuracy": float(cross.accuracy.median()),
            "cross_city_mean_macro_f1": float(cross.macro_f1_groups_ge_minimum.mean()),
            "cross_city_median_macro_f1": float(cross.macro_f1_groups_ge_minimum.median()),
            "cross_city_mean_weighted_f1": float(cross.weighted_f1.mean()),
            "cross_city_median_weighted_f1": float(cross.weighted_f1.median()),
            "cross_pooled_records": pooled["records"],
            "cross_pooled_accuracy": pooled["accuracy"],
            "cross_pooled_macro_f1": pooled["macro_f1_groups_ge_minimum"],
            "cross_pooled_weighted_f1": pooled["weighted_f1"],
        })
    summaries = pd.DataFrame(summary_rows)
    summaries.to_csv(arguments.output_dir / "source_model_summaries.csv", index=False)

    collapsed_k6 = summaries.loc[summaries.label_space.eq("collapsed_k6")].copy()
    overall = collapsed_k6.groupby("regime").agg(
        source_models=("source_city", "nunique"),
        mean_within_accuracy=("within_accuracy", "mean"),
        mean_within_macro_f1=("within_macro_f1", "mean"),
        mean_within_weighted_f1=("within_weighted_f1", "mean"),
        mean_source_balanced_cross_accuracy=("cross_city_mean_accuracy", "mean"),
        median_source_balanced_cross_accuracy=("cross_city_mean_accuracy", "median"),
        mean_source_balanced_cross_macro_f1=("cross_city_mean_macro_f1", "mean"),
        median_source_balanced_cross_macro_f1=("cross_city_mean_macro_f1", "median"),
        mean_source_balanced_cross_weighted_f1=("cross_city_mean_weighted_f1", "mean"),
        median_source_balanced_cross_weighted_f1=("cross_city_mean_weighted_f1", "median"),
    ).reset_index()
    overall.to_csv(arguments.output_dir / "overall_collapsed_k6_summary.csv", index=False)

    one = collapsed_k6.loc[collapsed_k6.regime.eq("one_city")].copy()
    prim = collapsed_k6.loc[collapsed_k6.regime.eq("primary")].copy()
    comparison = one.merge(prim, on=["source_city", "label_space"], suffixes=("_one_city", "_primary"))
    for metric in ("cross_city_mean_accuracy", "cross_city_mean_macro_f1", "cross_city_mean_weighted_f1"):
        comparison[f"delta_{metric}"] = comparison[f"{metric}_one_city"] - comparison[f"{metric}_primary"]
    comparison.to_csv(arguments.output_dir / "one_city_vs_primary_collapsed_k6.csv", index=False)

    metadata = {
        "source_cities": list(sources),
        "target_cities": targets,
        "source_models": len(sources),
        "target_cities_per_source": len(targets),
        "cross_city_targets_per_source": len(targets) - 1,
        "qa_screen": "excluded qa_flag_low_vegetated_height_with_lidar records",
        "minimum_qa_screened_test_records_per_city": arguments.minimum_test_records,
        "macro_f1_rule": (
            "calculated over target-city groups with at least "
            f"{arguments.minimum_group_records} screened test records"
        ),
        "primary_summary": "source-balanced: target cities averaged within source, then source models averaged equally",
        "comparability_checks_passed": True,
    }
    (arguments.output_dir / "analysis_metadata.json").write_text(
        json.dumps(metadata, indent=2), encoding="utf-8"
    )
    print("AUDIT\n", audit.to_string(index=False))
    print("\nCOLLAPSED_K6 SOURCE SUMMARIES\n", collapsed_k6.to_string(index=False))
    print("\nOVERALL COLLAPSED_K6\n", overall.to_string(index=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
